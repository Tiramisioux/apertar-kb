#!/bin/bash
# Rebuild old_normalizers.inc from a Core tree (read only): bash controls_make_old.sh <core-tree> > controls_old_normalizers.inc
C="$1/src/hardware"
echo "// Generated by controls_make_old.sh from Core $(git -C "$1" rev-parse --short HEAD) (read-only copies of the three normalizers)."
echo '#include "hardware/ButtonActionList.hpp"'
echo '#include <algorithm>'
echo '#include <cctype>'
echo '#include <string>'
for pair in "old_gpio GpioInput.cpp 27 58 108 202" "old_pcf Pcf8574Input.cpp 27 58 140 242" "old_neo NeoRotary4Input.cpp 40 71 121 215"; do
  set -- $pair
  echo "namespace $1 { namespace hardware = apertar::hardware;"
  sed -n "$3,$4p" "$C/$2" | awk '/^std::filesystem::path defaultHardwareConfigPath/{exit} {print}'
  sed -n "$5,$6p" "$C/$2"
  echo "} // namespace $1"
done
